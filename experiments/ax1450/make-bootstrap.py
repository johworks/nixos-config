#!/usr/bin/env python3
"""Generate the AX1450 persistent root-channel bootstrap.

Builds the router-side bootstrap script, its base64 payload for the unused
router-config flash partition, and the short loader command that the
auto-reboot scheduler cron executes after every boot (and daily).

The loader must stay well under busybox uci's ~2047-byte line limit for the
persisted autoreboot day value, so the full script is never inlined there:
it is stored once (as base64) in the router-config partition, which has no
boot-time consumer, and the loader reads it back with nvrammanager. The
loader also stays within the character set already proven to survive
TP-Link's XML config round trip: no '<', '>', '&', '%' or newlines.
"""

import argparse
import base64
from pathlib import Path
import shlex
import hashlib

SELF_HEAL_MARKER = "ax1450-selfheal"
SCRIPT_PATH = "/etc/ax1450/bootstrap.sh"
HOSTKEY_PATH = "/etc/ax1450/hostkey"
PID_FILE = "/tmp/ax1450-root.pid"
PAYLOAD_PARTITION = "router-config"
PAYLOAD_PATH = "/etc/ax1450/payload.b64"


def build_script(host_key_b64: str, public_keys: list[str], ap: str, port: int, allow: list[str]) -> str:
    accept_rules = "\n".join(
        f"ipt -p tcp --dport {port} -s {src} -j ACCEPT" for src in allow
    )
    key_installs = "\n".join(
        f'install_key {shlex.quote(key)}' for key in public_keys
    )
    return f"""#!/bin/sh
# Generated by experiments/ax1450/make-bootstrap.py; do not edit on the router.
set -eu
umask 077

# Exit when the root channel is already up (pid file names a live process).
pid=$(cat {PID_FILE} 2>/dev/null || true)
if [ -n "$pid" ] && [ -d "/proc/$pid" ]; then exit 0; fi

# Port is closed to everyone except the manager hosts; inserts keep the
# ACCEPT rules above the catch-all DROP.
ipt() {{ /usr/sbin/iptables -C INPUT "$@" >/dev/null 2>&1 || /usr/sbin/iptables -I INPUT 1 "$@"; }}
ipt -p tcp --dport {port} -j DROP
{accept_rules}

install_key() {{
  grep -qsF "$1" /etc/dropbear/authorized_keys 2>/dev/null || printf '%s\\n' "$1" >> /etc/dropbear/authorized_keys
}}

mkdir -p /etc/dropbear /etc/ax1450
printf '%s' '{host_key_b64}' | /usr/bin/openssl base64 -d -A > {HOSTKEY_PATH}
chmod 600 {HOSTKEY_PATH}
{key_installs}
chmod 700 /etc/dropbear
chmod 600 /etc/dropbear/authorized_keys

# Runtime self-heal: re-run this script every 30 minutes while the AP stays
# up. The boot-time crontab is regenerated from persisted config, and this
# line is re-added by the first run after each boot.
grep -q {SELF_HEAL_MARKER} /etc/crontabs/root 2>/dev/null || \\
  printf '%s\\n' '*/30 * * * * /bin/sh {SCRIPT_PATH} # {SELF_HEAL_MARKER}' >> /etc/crontabs/root

exec /usr/sbin/dropbear -L -s -j -k -6 -p {ap}:{port} -P {PID_FILE} -r {HOSTKEY_PATH}
"""


def build_loader() -> str:
    # ';' not '&&' and no redirections: '&'/'>'/'<' are not in the character
    # set proven to survive the vendor XML config round trip.
    loader = (
        f"mkdir -p /etc/ax1450; /usr/bin/nvrammanager -r {PAYLOAD_PATH}"
        f" -p {PAYLOAD_PARTITION}; /usr/bin/openssl base64 -d -A -in {PAYLOAD_PATH}"
        f" | tee {SCRIPT_PATH} | /bin/sh"
    )
    forbidden = "<>&%\n"
    found = [c for c in forbidden if c in loader]
    if found:
        raise ValueError(f"Loader contains XML/cron metacharacters: {found}")
    if len(loader) > 1500:
        raise ValueError(f"Loader too long for the uci line limit: {len(loader)}")
    return loader


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host-key", type=Path, required=True,
                        help="Dropbear-format RSA host key file to pin")
    parser.add_argument("--host-key-pub", type=Path, required=True,
                        help="Public host key from 'dropbearkey -y' (ssh-rsa ...)")
    parser.add_argument("--public-key", type=Path, required=True, action="append",
                        help="SSH public key allowed to connect (repeatable)")
    parser.add_argument("--ap", default="192.168.10.161")
    parser.add_argument("--port", type=int, default=2222)
    parser.add_argument("--allow", action="append", required=True,
                        help="Source IP allowed to reach the SSH port (repeatable)")
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    host_key_b64 = base64.b64encode(args.host_key.read_bytes()).decode()
    public_keys = [p.read_text().strip() for p in args.public_key]
    for key in public_keys:
        if not key.startswith("ssh-rsa ") or not key.split()[2]:
            raise ValueError(f"Not an ssh-rsa public key: {key[:40]}...")

    script = build_script(host_key_b64, public_keys, args.ap, args.port, args.allow)
    loader = build_loader()
    payload = base64.b64encode(script.encode()).decode()

    out = args.output_dir
    out.mkdir(mode=0o700, parents=True, exist_ok=True)
    script_path = out / "bootstrap.sh"
    script_path.write_text(script)
    script_path.chmod(0o600)
    command_path = out / "command.txt"
    command_path.write_text(loader + "\n")
    command_path.chmod(0o600)
    payload_path = out / "payload.b64"
    payload_path.write_text(payload)
    payload_path.chmod(0o600)

    # Convenience known_hosts line for the pinned host key.
    host_pub = args.host_key_pub.read_text().strip()
    if not host_pub.startswith("ssh-rsa "):
        raise ValueError("Host public key must be an ssh-rsa line from dropbearkey -y")
    known_hosts = out / "known_hosts.pinned"
    known_hosts.write_text(f"[{args.ap}]:{args.port} ssh-rsa {host_pub.split()[1]}\n")
    known_hosts.chmod(0o600)

    print(f"bootstrap.sh: {len(script)} bytes, payload.b64: {len(payload)} bytes, loader: {len(loader)} bytes")
    print(f"Day value: '* {loader} #' ({len(loader) + 4} bytes, under the uci 2047-byte line limit)")
    print("Payload SHA256:", hashlib.sha256(payload.encode()).hexdigest())
    print(f"SSH: {args.ap}:{args.port}, key-only, sources: {', '.join(args.allow)}")
    print(f"Install: write payload.b64 to the {PAYLOAD_PARTITION} partition, then set the autoreboot day value.")


if __name__ == "__main__":
    main()
